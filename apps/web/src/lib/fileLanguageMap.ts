const COMPOUND_EXTENSION_PATTERN = /\.([^/\\]+\.[^/\\]+)$/;
const SIMPLE_EXTENSION_PATTERN = /\.([^.]+)$/;

/** Highlighter language for a file name: exact name, then compound, then simple extension. */
export function resolveLanguageFromFileName(fileName: string): string {
  const exact = lookup(fileName);
  if (exact !== undefined) return exact;
  const compound = COMPOUND_EXTENSION_PATTERN.exec(fileName)?.[1];
  if (compound !== undefined) {
    const compoundLanguage = lookup(compound);
    if (compoundLanguage !== undefined) return compoundLanguage;
  }
  const simple = SIMPLE_EXTENSION_PATTERN.exec(fileName)?.[1];
  return (simple === undefined ? undefined : lookup(simple)) ?? "text";
}

function lookup(key: string): string | undefined {
  // Own keys only: a file named "constructor" must not resolve to Object.prototype.
  return Object.hasOwn(FILE_NAME_TO_LANGUAGE, key) ? FILE_NAME_TO_LANGUAGE[key] : undefined;
}
